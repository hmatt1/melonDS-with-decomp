# ---------------------------------------------------------------- Python

def py_record_format(r):
    fmt = "<"
    for fname, ftype, *rest in r["fields"]:
        m = re.fullmatch(r"(u8|char)\[(\d+)\]", ftype)
        if m:
            fmt += f"{m.group(2)}s"
        else:
            fmt += RECORD_TYPES[ftype][1]
    return fmt


def py_type(fi, types):
    e = fi["elem"]
    t = PY_SCALAR.get(e, f"\"{e}\"" if e in types else "Any")
    if e in types:
        t = e
    if fi["array"]:
        t = f"List[{t}]"
    if fi["optional"]:
        t = f"Optional[{t}]"
    return t


def py_default(fi):
    if fi["optional"]:
        return "None"
    if fi["array"]:
        return "field(default_factory=lambda: " + repr(fi["default"] or []) + ")"
    d = fi["default"]
    e = fi["elem"]
    if d is not None:
        return repr(d)
    if e in ("u8", "u16", "u32", "u64", "i32", "addr"):
        return "0"
    if e == "f64":
        return "0.0"
    if e == "bool":
        return "False"
    if e == "string":
        return "\"\""
    if e == "json":
        return "None"
    return None  # nested object: default_factory


def gen_python(schema):
    api = schema["api"]
    types = api["types"]
    o = []
    w = o.append
    w("# GENERATED by tools/workbench/wbgen.py from src/workbench/schema/workbench.schema.json. Do not edit.")
    w("\"\"\"Record layouts, enums and API types for the DS Decomp Workbench.\"\"\"")
    w("from __future__ import annotations")
    w("")
    w("import enum")
    w("import struct")
    w("from dataclasses import dataclass, field, fields, is_dataclass")
    w("from typing import Any, Dict, List, Optional")
    w("")
    w(f"SCHEMA_VERSION = {schema['schema_version']}")
    w(f"API_VERSION = {json.dumps(schema['api_version'])}")
    w("")
    for ename, e in schema["enums"].items():
        base = "enum.IntFlag" if e.get("flags") else "enum.IntEnum"
        w(f"class {ename}({base}):")
        if e.get("doc"):
            w(f"    {json.dumps(e['doc'])}")
        for k, v in e["values"].items():
            w(f"    {k} = {v}")
        w("")
    w("")
    for rname, r in schema["records"].items():
        fmt = py_record_format(r)
        w("@dataclass")
        w(f"class {rname}:")
        if r.get("doc"):
            w(f"    {json.dumps(r['doc'])}")
        for fname, ftype, *rest in r["fields"]:
            pt = "bytes" if "[" in ftype else "int"
            w(f"    {fname}: {pt}")
        w(f"    FORMAT = {json.dumps(fmt)}")
        w(f"    SIZE = {r['size']}")
        w("")
        w("    @classmethod")
        w(f"    def unpack_from(cls, buf, offset: int = 0) -> \"{rname}\":")
        w("        return cls(*struct.unpack_from(cls.FORMAT, buf, offset))")
        w("")
        w("    @classmethod")
        w(f"    def iter_unpack(cls, buf):")
        w("        for t in struct.iter_unpack(cls.FORMAT, buf):")
        w("            yield cls(*t)")
        w("")
        w("    def pack(self) -> bytes:")
        w("        return struct.pack(self.FORMAT, " + ", ".join(f"self.{f[0]}" for f in r["fields"]) + ")")
        w("")
        w(f"assert struct.calcsize({rname}.FORMAT) == {r['size']}")
        w("")
    w("")
    w("def _from_json(tp, v):")
    w("    if v is None:")
    w("        return None")
    w("    if isinstance(tp, type) and is_dataclass(tp):")
    w("        return tp.from_dict(v)")
    w("    return v")
    w("")
    w("")
