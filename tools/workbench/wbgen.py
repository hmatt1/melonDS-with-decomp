#!/usr/bin/env python3
"""DS Decomp Workbench code generator.

Reads src/workbench/schema/workbench.schema.json and generates:

  --cpp-records DIR   WBRecords.h        record layouts and enums (melonDS core, no Qt)
  --cpp-api DIR       WBApi.h, WBApi.cpp API request/response types with Qt JSON conversion
  --python FILE       _generated.py      enums, record parsers, API dataclasses and client methods

The schema is the single definition of every shared layout. Never edit the outputs by hand.
"""

import argparse
import json
import keyword
import os
import re
import sys

SCALARS_CPP = {
    "u8": "melonDS::u8", "u16": "melonDS::u16", "u32": "melonDS::u32", "u64": "melonDS::u64",
    "i32": "melonDS::s32", "f64": "double", "bool": "bool", "string": "QString", "addr": "melonDS::u32",
    "json": "QJsonValue",
}
RECORD_TYPES = {"u8": ("melonDS::u8", "B", 1), "u16": ("melonDS::u16", "H", 2), "u32": ("melonDS::u32", "I", 4), "u64": ("melonDS::u64", "Q", 8)}
PY_SCALAR = {"u8": "int", "u16": "int", "u32": "int", "u64": "int", "i32": "int", "f64": "float", "bool": "bool",
             "string": "str", "addr": "int", "json": "Any"}


def load_schema(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", newline="") as f:
            if f.read() == text:
                return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def snake(name):
    # MainRAM -> main_ram, ARM7WRAM -> arm7_wram, LastWriteDMA -> last_write_dma
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


# ---------------------------------------------------------------- records (C++)

def parse_record_field(ftype):
    m = re.fullmatch(r"(u8|char)\[(\d+)\]", ftype)
    if m:
        return ("array", "char" if m.group(1) == "char" else "melonDS::u8", int(m.group(2)))
    if ftype not in RECORD_TYPES:
        raise SystemExit(f"unknown record field type {ftype}")
    return ("scalar", RECORD_TYPES[ftype][0], RECORD_TYPES[ftype][2])


def gen_cpp_records(schema):
    out = []
    w = out.append
    w("// GENERATED by tools/workbench/wbgen.py from src/workbench/schema/workbench.schema.json. Do not edit.")
    w("#ifndef WB_RECORDS_H")
    w("#define WB_RECORDS_H")
    w("")
    w("#include <cstddef>")
    w("#include \"types.h\"")
    w("")
    w("namespace melonDS::WB")
    w("{")
    w(f"constexpr u32 SchemaVersion = {schema['schema_version']};")
    w(f"constexpr const char* ApiVersion = \"{schema['api_version']}\";")
    w("")
    for ename, e in schema["enums"].items():
        utype = RECORD_TYPES[e["type"]][0]
        if e.get("doc"):
            w(f"// {e['doc']}")
        if e.get("flags"):
            w(f"namespace {ename}")
            w("{")
            for k, v in e["values"].items():
                w(f"    constexpr {utype} {k} = {v};")
            w(f"    constexpr const char* Names[] = {{{', '.join(chr(34) + snake(k) + chr(34) for k in e['values'])}}};")
            w(f"    constexpr {utype} Values[] = {{{', '.join(str(v) for v in e['values'].values())}}};")
            w(f"    constexpr int Count = {len(e['values'])};")
            w("}")
        else:
            w(f"enum class {ename} : {utype}")
            w("{")
            for k, v in e["values"].items():
                w(f"    {k} = {v},")
            w("};")
            w(f"inline const char* {ename}Name({utype} v)")
            w("{")
            w("    switch (v)")
            w("    {")
            for k, v in e["values"].items():
                w(f"    case {v}: return \"{snake(k)}\";")
            w("    default: return \"unknown\";")
            w("    }")
            w("}")
        w("")

    w("#pragma pack(push, 1)")
    for rname, r in schema["records"].items():
        if r.get("doc"):
            w(f"// {r['doc']}")
        w(f"struct {rname}")
        w("{")
        total = 0
        for fname, ftype, *rest in r["fields"]:
            kind, ctype, size = parse_record_field(ftype)
            doc = rest[0] if rest and rest[0] else ""
            cm = f" // {doc}" if doc else ""
            if kind == "array":
                w(f"    {ctype} {fname}[{size}];{cm}")
            else:
                w(f"    {ctype} {fname};{cm}")
            total += size
        w("};")
        if total != r["size"]:
            raise SystemExit(f"record {rname}: fields add up to {total}, schema says {r['size']}")
        w(f"static_assert(sizeof({rname}) == {r['size']}, \"{rname} layout mismatch\");")
        w("")
    w("#pragma pack(pop)")
    w("")
    w("}")
    w("#endif")
    w("")
    return "\n".join(out)


# ---------------------------------------------------------------- API (C++)

def api_field(f):
    name, ftype, doc = f[0], f[1], f[2]
    if keyword.iskeyword(name):
        # the Python dataclasses use field names as attributes
        raise SystemExit(f"api field '{name}' is a Python keyword: rename it")
    has_default = len(f) > 3
    default = f[3] if has_default else None
    optional = ftype.endswith("?")
    base = ftype[:-1] if optional else ftype
    is_array = base.endswith("[]")
    elem = base[:-2] if is_array else base
    return dict(name=name, type=ftype, base=base, elem=elem, array=is_array, optional=optional,
                has_default=has_default, default=default, doc=doc)


def cpp_elem_type(elem, types):
    if elem in SCALARS_CPP:
        return SCALARS_CPP[elem]
    if elem in types:
        return elem
    raise SystemExit(f"unknown api type {elem}")


def cpp_field_type(fi, types):
    t = cpp_elem_type(fi["elem"], types)
    if fi["array"]:
        t = f"std::vector<{t}>"
    if fi["optional"]:
        t = f"std::optional<{t}>"
    return t


def cpp_default(fi):
    if fi["optional"]:
        return ""
    d = fi["default"]
    e = fi["elem"]
    if fi["array"]:
        if d:
            vals = ", ".join(cpp_literal(e, v) for v in d)
            return f" = {{{vals}}}"
        return ""
    if d is None:
        if e in ("u8", "u16", "u32", "u64", "i32", "addr"):
            return " = 0"
        if e == "f64":
            return " = 0.0"
        if e == "bool":
            return " = false"
        return ""
    return " = " + cpp_literal(e, d)


def cpp_literal(e, v):
    if e == "string":
        return "QStringLiteral(" + json.dumps(v) + ")"
    if e == "bool":
        return "true" if v else "false"
    if e == "u64":
        return f"{v}ULL"
    if e in ("u32", "addr"):
        return f"{v}U"
    return str(v)


